#!/usr/bin/env node
/**
 * Extract the `--ls-*` variables a Logseq build declares under its accent
 * palettes, into a test fixture.
 *
 * The coverage test asserts the theme overrides every one of them (or
 * allowlists it with a reason). That set is what caught the eight variables
 * — `--ls-guideline-color` among them — that were leaking Logseq's solarized
 * teal into an otherwise-Adwaita UI.
 *
 * Regenerate whenever testing against a new Logseq version:
 *
 *   node scripts/extract-logseq-vars.mjs og  ~/.local/opt/logseq-og/resources/app/css/style.css
 *   node scripts/extract-logseq-vars.mjs db  /path/to/Logseq/resources/app/css/style.css
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';

const [target, cssPath] = process.argv.slice(2);
if (!target || !cssPath) {
  console.error('usage: extract-logseq-vars.mjs <target-id> <path/to/style.css>');
  process.exit(2);
}

const css = readFileSync(cssPath.replace(/^~/, process.env.HOME), 'utf8');

// Logseq declares a full palette per accent, e.g.
//   html[data-theme=dark][data-color=logseq]{--ls-primary-background-color:#002b36; ...}
// The "logseq" swatch is the one that ships enabled by default, so it is the
// palette a fresh install actually renders with.
const blocks = [...css.matchAll(/html\[data-theme=(dark|light)\]\[data-color=logseq\]\{([^}]*)\}/g)];
if (!blocks.length) {
  console.error(`no [data-color=logseq] palette found in ${cssPath}`);
  process.exit(1);
}

const vars = {};
for (const [, mode, body] of blocks) {
  for (const m of body.matchAll(/(--ls-[a-z0-9-]+)\s*:\s*([^;]+)/g)) {
    (vars[mode] ??= {})[m[1]] = m[2].trim();
  }
}

const out = {
  _comment:
    'Generated by scripts/extract-logseq-vars.mjs — the --ls-* variables this Logseq ' +
    'build declares under its default "logseq" accent palette. Do not hand-edit; regenerate.',
  target,
  source: cssPath,
  generated: new Date().toISOString().slice(0, 10),
  vars,
};

const dest = join(dirname(new URL(import.meta.url).pathname), '..', 'tests/fixtures', `logseq-vars.${target}.json`);
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');

const counts = Object.entries(vars).map(([m, v]) => `${m}=${Object.keys(v).length}`).join(' ');
console.log(`wrote ${dest} (${counts})`);
